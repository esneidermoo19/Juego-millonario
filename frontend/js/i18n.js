  function translateTextNode(node) {
    if (!originals.has(node)) originals.set(node, node.nodeValue);
    const original = originals.get(node);
    const key = original.trim();
    if (!key) return;
    const leading = original.match(/^\s*/)?.[0] || "";
    const trailing = original.match(/\s*$/)?.[0] || "";
    let translated = translations[key];
    if (language === "en" && !translated && key.startsWith("Respuesta incorrecta. Llegaste hasta la pregunta ")) {
      const number = key.match(/pregunta\s+(\d+)/)?.[1] || "0";
      translated = `Incorrect answer. You made it to question ${number}. Try again!`;
    }
    node.nodeValue = language === "en" && translated
      ? `${leading}${translated}${trailing}`
      : original;
  }

  function translateElement(element) {
    const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) translateTextNode(node);
    if (element.nodeType === Node.ELEMENT_NODE) {
      for (const attr of ["title", "placeholder", "aria-label"]) {
        const value = element.getAttribute(attr);
        const dataKey = `original${attr}`;
        if (value && !element.dataset[dataKey]) element.dataset[dataKey] = value;
        const original = element.dataset[dataKey];
        if (original) {
          element.setAttribute(
            attr,
            language === "en" ? (translations[original] || original) : original
          );
        }
      }
    }
  }

